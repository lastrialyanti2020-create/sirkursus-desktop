    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {                                        
        String nim = txtNim.getText().trim();
        String nama = txtNama.getText().trim();
        String prodi = txtProdi.getText().trim();
        String noHp = txtNoHp.getText().trim();
        String email = txtEmail.getText().trim();

        String jenisKelamin = "";
        if (rbLaki.isSelected()) {
            jenisKelamin = "L";
        } else if (rbPerempuan.isSelected()) {
            jenisKelamin = "P";
        }

        if (nim.isEmpty() || nama.isEmpty() || prodi.isEmpty() || jenisKelamin.isEmpty()) {
            JOptionPane.showMessageDialog(
                this,
                "NIM, nama, jenis kelamin, dan prodi wajib diisi.",
                "Validasi",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        try {
            Peserta peserta = new Peserta(nim, nama, jenisKelamin, prodi, noHp, email);
            PesertaDAO pesertaDAO = new PesertaDAO();

            if (pesertaDAO.insert(peserta)) {
                JOptionPane.showMessageDialog(this, "Data peserta berhasil disimpan.");
                resetForm();
            } else {
                JOptionPane.showMessageDialog(this, "Data tidak tersimpan.");
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                this,
                "Gagal menyimpan data:\n" + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }                                       

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {                                        
        int jawab = JOptionPane.showConfirmDialog(
            this,
            "Kosongkan seluruh input?",
            "Konfirmasi Reset",
            JOptionPane.YES_NO_OPTION
        );
        if (jawab == JOptionPane.YES_OPTION) {
            resetForm();
        }
    }                                       

    private void resetForm() {
        txtNama.setText("");
        txtNim.setText("");
        txtProdi.setText("");
        txtNoHp.setText("");
        txtEmail.setText("");
        buttonGroup1.clearSelection();
        txtNama.requestFocusInWindow();
    }

